// Builds index.html for GitHub Pages from redline-garage.html.
// redline-garage.html is an artifact fragment (no <html>/<head>/<body>); the artifact host wraps it
// with the skeleton below, so Pages gets the same wrapper.
// Usage: npm run build
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const body = fs.readFileSync(path.join(root, 'redline-garage.html'), 'utf8');

const icon = "data:image/svg+xml," + encodeURIComponent(
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40"><rect width="40" height="40" rx="10" fill="#e3262f"/>' +
  '<path d="M9 27a12 12 0 1 1 22 0" fill="none" stroke="#fff" stroke-width="2.6" stroke-linecap="round"/>' +
  '<path d="M20 27l7-9" stroke="#fff" stroke-width="2.6" stroke-linecap="round"/><circle cx="20" cy="27" r="2.4" fill="#fff"/></svg>');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="A 3D studio for customising sports, hyper and rally cars: paint, rims, body kits, liveries and stance.">
<link rel="icon" href="${icon}">
<!-- generated by tools/build-pages.mjs from redline-garage.html; edit that file, not this one -->
<style>
:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0;font:14px/1.4 system-ui,-apple-system,"Segoe UI",sans-serif;background:#fafafa}
img{max-width:100%}
[hidden]{display:none!important}
</style>
</head>
<body>
${body}
</body>
</html>
`;
fs.writeFileSync(path.join(root, 'index.html'), html);
fs.writeFileSync(path.join(root, '.nojekyll'), '');
console.log('index.html written (' + (html.length / 1024).toFixed(0) + ' KB)');
